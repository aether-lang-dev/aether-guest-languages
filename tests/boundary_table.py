#!/usr/bin/env python3
"""The README's boundary table, from a run of the shared boundary tests.

  boundary_table.py check|write <lang>           the contained child's grid,
                                                 from build/boundary-<lang>.tsv
  boundary_table.py check|write <lang> inproc    the in-process grid, from
                                                 build/boundary-inproc-<lang>.tsv
  boundary_table.py check|write <lang> invoke    the host calling the guest, from
                                                 build/invoke-<lang>.tsv

check fails when <lang>/README.md's table disagrees with the run; write rewrites it.

The table is between <!-- boundary:begin --> and <!-- boundary:end --> in
<lang>/README.md, just before "## What crosses the boundary". Cells are classes
(ok, n/a, error, killed, no call) and, for a value the worker changed, what the
host saw. tests/readme_tables.sh summarises these tables into the first README
table, so a README that claims a type the tests did not pass fails the run.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPE_ROWS = ["str", "str-empty", "str-nonascii", "str-nul", "str-astral", "str-60k", "int", "int-neg", "int-max", "int-min",
             "float", "bool-true", "bool-false", "null", "array", "map", "nested"]
SPECIAL = [("nest", "a call inside a call's argument"), ("refuse", "an error answer (`FAIL`) to a call"),
           ("wait", "a cancel while a call waits"), ("loop", "a cancel inside a guest loop"),
           ("big-up", "a 100,000-byte argument"), ("big-down", "a 100,000-byte answer")]
CHILD = dict(name="boundary", file="boundary-%s.tsv", where="the contained child", head="Boundary tests",
             special=SPECIAL)
INPROC_SPECIAL = [("nest", "a call inside a call's argument"), ("refuse", "an error raised by the host function"),
                  ("wait", "a cancel while a call waits"), ("loop", "a limit on a guest loop"),
                  ("big-up", "a 100,000-byte argument"), ("big-down", "a 100,000-byte answer")]
INPROC = dict(name="boundary-inproc", file="boundary-inproc-%s.tsv", where="the in-process bridge", head="Boundary tests, in-process",
              special=INPROC_SPECIAL)
INVOKE_SPECIAL = [("relay", "an export that calls a mounted host function"), ("state", "state between invocations (a counter, three calls)"),
                  ("raise", "an export that raises, then another call"), ("loop", "a cancel inside an export's loop"),
                  ("wait", "a cancel while an export waits on a host call"), ("big", "a 100,000-byte `RETURN`"),
                  ("args", "three arguments of different types"), ("big-arg", "a 100,000-byte `INVOKE` argument"),
                  ("maxframe", "a host that reads frames of 4 KiB (`MAXFRAME`)"),
                  ("unexported", "`INVOKE` of a name the guest did not export"), ("end", "`END`"),
                  ("none", "a script that exports nothing"),
                  ("txn", "notify, then fetch: two transactions, an unknown id")]
INVOKE_ROWS = ["guest-export-called", "guest-export-slow", "guest-export-silent", "guest-export-oversize",
               "guest-export-raises", "guest-reenters-while-called", "guest-export-flood",
               "guest-export-malformed", "guest-after-end"]
INVOKE = dict(name="invoke", file="invoke-%s.tsv", where="the host calling the guest", head="Host calls guest",
              special=INVOKE_SPECIAL)
MODE = CHILD

def cell(outcome, detail):
    if outcome == "differs":
        return "differs: " + detail
    if detail and MODE is INVOKE and outcome in ("error", "not held", "left out", "other"):
        return outcome + ": " + detail
    return outcome

def load(path):
    res = {}
    for line in open(path, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) >= 3:
            res[(p[0], p[1])] = cell(p[2], p[3] if len(p) > 3 else "").replace("|", "\\|")
    return res

def begin():
    return "<!-- %s:begin: generated by sh tests/run.sh --write-parity, from build/%s -->" % (MODE["name"], MODE["file"].replace("%s", "*"))

def end():
    return "<!-- %s:end -->" % MODE["name"]

def render(res):
    out = [begin(),
           "| case | guest to host | host to guest, passed back |", "|---|---|---|"]
    for t in TYPE_ROWS:
        out.append("| `%s` | %s | %s |" % (t, res.get((t, "up"), "n/a"), res.get((t, "down"), "n/a")))
    for k, label in MODE["special"]:
        out.append("| %s (`%s`) | %s | |" % (label, k, res.get((k, "-"), "n/a")))
    out.append(end())
    return "\n".join(out) + "\n"

def render_invoke(res):
    out = [begin(),
           "| case | guest to host, as a `RETURN` value | host to guest, as an `INVOKE` argument, returned |", "|---|---|---|"]
    for t in TYPE_ROWS:
        out.append("| `%s` | %s | %s |" % (t, res.get((t, "ret"), "n/a"), res.get((t, "arg"), "n/a")))
    for k, label in INVOKE_SPECIAL:
        out.append("| %s (`%s`) | %s | |" % (label, k, res.get((k, "-"), "n/a")))
    out += ["", "| host-calls-guest row | outcome |", "|---|---|"]
    for r in INVOKE_ROWS:
        out.append("| `%s` | %s |" % (r, res.get((r, "-"), "n/a")))
    out.append(end())
    return "\n".join(out) + "\n"

def parse_invoke(text):
    """{(case, ret|arg|-): cell} from a README's host-calls-guest grid, or None."""
    m = re.search(block_re(INVOKE), text, re.S)
    if not m:
        return None
    res = {}
    for l in m.group(1).split("\n"):
        if not l.startswith("|"):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", l.strip())[1:-1]]
        if len(cells) < 2 or cells[0] in ("case", "---", "host-calls-guest row"):
            continue
        mm = re.match(r"`([a-z0-9-]+)`$", cells[0])
        if mm and len(cells) >= 3:
            res[(mm.group(1), "ret")] = cells[1]; res[(mm.group(1), "arg")] = cells[2]
            continue
        if mm:
            res[(mm.group(1), "-")] = cells[1]
            continue
        mm = re.match(r".*\(`([a-z-]+)`\)$", cells[0])
        if mm:
            res[(mm.group(1), "-")] = cells[1]
    return res

def block_re(mode):
    return re.escape("<!-- %s:begin" % mode["name"]) + r".*?-->\n(.*?)" + re.escape("<!-- %s:end -->" % mode["name"])

ROWS = [(t, "up") for t in TYPE_ROWS]

def keys_of(mode):
    """The grid's rows in order: (key, ...) where a type row has both directions."""
    return [(t, None) for t in TYPE_ROWS] + [(k, label) for k, label in mode["special"]]

def parse_readme_table(text, mode=None):
    """The results back from a README's table, or None: {(case, dir): cell} for the first
    result column pair (the contained child's grid, or the in-process grid's Linux columns)."""
    return parse_columns(text, mode or CHILD, 0)

def parse_columns(text, mode, pair):
    """pair 0: the first two result columns, pair 1: the in-process grid's macOS columns."""
    m = re.search(block_re(mode), text, re.S)
    if not m:
        return None
    res = {}
    for l in m.group(1).split("\n"):
        if not l.startswith("|"):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", l.strip())[1:-1]]
        if len(cells) < 3 or cells[0] in ("case", "---"):
            continue
        a, b = cells[1 + 2 * pair], cells[2 + 2 * pair] if len(cells) > 2 + 2 * pair else ""
        mm = re.match(r"`([a-z0-9-]+)`$", cells[0])
        if mm:
            res[(mm.group(1), "up")] = a; res[(mm.group(1), "down")] = b
            continue
        mm = re.match(r".*\(`([a-z-]+)`\)$", cells[0])
        if mm:
            res[(mm.group(1), "-")] = a
    return res

def this_platform():
    return "macos" if sys.platform == "darwin" else ("linux" if sys.platform.startswith("linux") else None)

def render_inproc(linux, mac):
    """linux and mac: {(case, dir): cell} or None (not run). A macOS cell that equals Linux's reads 'same'."""
    out = [begin(), "| case | guest to host | host to guest, passed back | macOS: guest to host | macOS: host to guest |",
           "|---|---|---|---|---|"]
    def cell(d, k):
        l = (linux or {}).get(k, "(not run)")
        m = (mac or {}).get(k, "(not run)")
        return l, ("same" if m == l and mac is not None and linux is not None else m)
    for t in TYPE_ROWS:
        lu, mu = cell(None, (t, "up")); ld, md = cell(None, (t, "down"))
        out.append("| `%s` | %s | %s | %s | %s |" % (t, lu, ld, mu, md))
    for k, label in MODE["special"]:
        l, m = cell(None, (k, "-"))
        out.append("| %s (`%s`) | %s | | %s | |" % (label, k, l, m))
    out.append(end())
    return "\n".join(out) + "\n"

def mac_differences(text):
    """The cases where a README's macOS cell is not 'same' (macOS gave a different result)."""
    mac = parse_columns(text, INPROC, 1) or {}
    return sorted({k[0] for k, v in mac.items() if v not in ("same", "(not run)", "")})

def main():
    global MODE
    what, lang = sys.argv[1], sys.argv[2]
    mode_arg = sys.argv[3] if len(sys.argv) > 3 else ""
    MODE = INPROC if mode_arg == "inproc" else (INVOKE if mode_arg == "invoke" else CHILD)
    run = os.path.join(ROOT, "build", MODE["file"] % lang)
    readme = os.path.join(ROOT, lang, "README.md")
    if not os.path.exists(run):
        print("  [SKIP] boundary table (%s, %s): nothing was recorded" % (lang, MODE["where"])); return 0
    text = open(readme, encoding="utf-8").read()
    if MODE is INPROC:
        plat = this_platform()
        if plat is None:
            print("  [SKIP] boundary table (%s, in-process): only Linux and macOS are recorded" % lang); return 0
        mine = load(run)
        linux = mine if plat == "linux" else parse_columns(text, INPROC, 0)
        mac_abs = mine if plat == "macos" else None
        if plat == "macos":
            want = render_inproc(linux, mac_abs)
        else:
            # keep the macOS columns as the README has them: they are checked by a macOS run
            old = parse_columns(text, INPROC, 1)
            lin = mine
            lines = ["| case | guest to host | host to guest, passed back | macOS: guest to host | macOS: host to guest |", "|---|---|---|---|---|"]
            want_rows = [begin(), lines[0], lines[1]]
            for t in TYPE_ROWS:
                want_rows.append("| `%s` | %s | %s | %s | %s |" % (t, lin.get((t, "up"), "n/a"), lin.get((t, "down"), "n/a"),
                                                                    (old or {}).get((t, "up"), "(not run)"), (old or {}).get((t, "down"), "(not run)")))
            for k, label in MODE["special"]:
                want_rows.append("| %s (`%s`) | %s | | %s | |" % (label, k, lin.get((k, "-"), "n/a"), (old or {}).get((k, "-"), "(not run)")))
            want_rows.append(end())
            want = "\n".join(want_rows) + "\n"
    elif MODE is INVOKE:
        want = render_invoke(load(run))
    else:
        want = render(load(run))
    m = re.search(re.escape("<!-- %s:begin" % MODE["name"]) + r".*?-->\n.*?" + re.escape(end()) + "\n", text, re.S)
    if what == "check":
        if MODE is INPROC and plat == "linux":
            # only the Linux columns are this run's to check
            got = parse_columns(text, INPROC, 0)
            exp = parse_columns(want, INPROC, 0)
            same = got == exp
        elif MODE is INPROC:
            got = parse_columns(text, INPROC, 1); exp = parse_columns(want, INPROC, 1)
            same = got == exp and parse_columns(text, INPROC, 0) == parse_columns(want, INPROC, 0)
        else:
            same = bool(m) and m.group(0) == want
        if not m or not same:
            print("  [FAIL] boundary table (%s, %s): the README's table differs from this run (sh tests/run.sh --write-parity rewrites it)" % (lang, MODE["where"]))
            if m:
                a, b = m.group(0).split("\n"), want.split("\n")
                shown = 0
                for x, y in zip(a, b):
                    if x != y and shown < 12:
                        print("    README: %s\n    run:    %s" % (x, y)); shown += 1
            return 1
        print("  [PASS] boundary table (%s, %s): the README's table agrees with this run" % (lang, MODE["where"])); return 0
    if m:
        text = text[:m.start()] + want + text[m.end():]
    else:
        h = "## What crosses the boundary"
        i = text.index(h)
        if MODE is INVOKE:
            intro = ("## Host calls guest\n\nThe other direction (`tests/boundary.py run-invoke`, run by `tests/test_invoke.sh`): a script per case that exports "
                     "functions, written in %s (the `x:` snippets in `containment/boundary.tsv`), run in this language's worker with a plan of invocations "
                     "from the host in `tests/lib/invoke`. A type crosses as a `RETURN` value when the export returns it written in the language, and as an "
                     "`INVOKE` argument when the export hands back what it was given. The second table holds the host-calls-guest safety rows by name: "
                     "`held`, `stricter` (refused earlier than the row asks), `left out` (the language cannot express it), or `not held`, which fails "
                     "the run. Nothing in the tests lists what a worker can do.\n\n" % lang)
        elif MODE is CHILD:
            intro = ("## Boundary tests\n\nThe shared tests in `tests/boundary.py`, run in this language's worker (`tests/test_boundary.sh`): one script per case, written in %s "
                     "(`containment/boundary.tsv`), and what the host saw on the wire. `ok` means the value crossed as the same JSON value; `n/a` means "
                     "the language has no way to write the case; anything else is what happened instead. Nothing in the tests lists what a worker can do.\n\n" % lang)
        else:
            intro = ("## Boundary tests, in-process\n\nThe same cases (`tests/boundary.py run-inproc`) against this language's bridge in this process, through the API it "
                     "really has (`containment/boundary_host.ae`, an Aether program written against it). There is no wire: \"what the host saw\" is what its typed readers "
                     "made of the argument, so `differs` says what was lost. `ok` means the value came back as the same JSON value; `n/a` means the bridge has no call that "
                     "could express the case; `refused` is a deliberate, documented refusal. Nothing in the tests lists what a bridge can do. For a table the host can build "
                     "one but not read one, so a table read back in the host is a tag. The columns are Linux's; the macOS columns read `same` where macOS gave the same "
                     "result and say what it gave where it did not.\n\n")
        text = text[:i] + intro + want + "\n" + text[i:]
    open(readme, "w", encoding="utf-8").write(text)
    print("  [PASS] boundary table (%s, %s): wrote it" % (lang, MODE["where"])); return 0

if __name__ == "__main__":
    sys.exit(main())
