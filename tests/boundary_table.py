#!/usr/bin/env python3
"""The README's boundary table, from a run of the shared boundary tests.

  boundary_table.py check <lang>   fail when <lang>/README.md's table disagrees
                                   with build/boundary-<lang>.tsv
  boundary_table.py write <lang>   rewrite it from the run

The table is between <!-- boundary:begin --> and <!-- boundary:end --> in
<lang>/README.md, just before "## What crosses the boundary". Cells are classes
(ok, n/a, error, killed, no call) and, for a value the worker changed, what the
host saw. tests/readme_tables.sh summarises these tables into the first README
table, so a README that claims a type the tests did not pass fails the run.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPE_ROWS = ["str", "str-empty", "str-nonascii", "str-nul", "str-astral", "str-60k", "int", "int-neg", "int-max", "int-min",
             "float", "bool-true", "bool-false", "null", "array", "map", "nested"]
SPECIAL = [("nest", "a call inside a call's argument"), ("refuse", "an error answer (`FAIL`) to a call"),
           ("wait", "a cancel while a call waits"), ("loop", "a cancel inside a guest loop"),
           ("big-up", "a 100,000-byte argument"), ("big-down", "a 100,000-byte answer")]
BEGIN = "<!-- boundary:begin: generated by sh tests/run.sh --write-parity, from build/boundary-*.tsv -->"
END = "<!-- boundary:end -->"

def cell(outcome, detail):
    if outcome == "differs":
        return "differs: " + detail
    return outcome

def load(path):
    res = {}
    for line in open(path, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) >= 3:
            res[(p[0], p[1])] = cell(p[2], p[3] if len(p) > 3 else "").replace("|", "\\|")
    return res

def render(res):
    out = [BEGIN,
           "| case | guest to host | host to guest, passed back |", "|---|---|---|"]
    for t in TYPE_ROWS:
        out.append("| `%s` | %s | %s |" % (t, res.get((t, "up"), "n/a"), res.get((t, "down"), "n/a")))
    for k, label in SPECIAL:
        out.append("| %s (`%s`) | %s | |" % (label, k, res.get((k, "-"), "n/a")))
    out.append(END)
    return "\n".join(out) + "\n"

def parse_readme_table(text):
    """The results back from a README's table, or None."""
    m = re.search(re.escape(BEGIN[:20]) + r".*?-->\n(.*?)" + re.escape(END), text, re.S)
    if not m:
        return None
    res = {}
    for l in m.group(1).split("\n"):
        mm = re.match(r"\| `([a-z0-9-]+)` \| (.*?) \| (.*?) \|$", l)
        if mm:
            res[(mm.group(1), "up")] = mm.group(2); res[(mm.group(1), "down")] = mm.group(3)
            continue
        mm = re.match(r"\| .*\(`([a-z-]+)`\) \| (.*?) \| \|$", l)
        if mm:
            res[(mm.group(1), "-")] = mm.group(2)
    return res

def main():
    what, lang = sys.argv[1], sys.argv[2]
    run = os.path.join(ROOT, "build", "boundary-%s.tsv" % lang)
    readme = os.path.join(ROOT, lang, "README.md")
    if not os.path.exists(run):
        print("  [SKIP] boundary table (%s): nothing was recorded" % lang); return 0
    want = render(load(run))
    text = open(readme, encoding="utf-8").read()
    m = re.search(re.escape(BEGIN[:20]) + r".*?-->\n.*?" + re.escape(END) + "\n", text, re.S)
    if what == "check":
        if not m or m.group(0) != want:
            print("  [FAIL] boundary table (%s): the README's table differs from this run (sh tests/run.sh --write-parity rewrites it)" % lang)
            if m:
                a, b = m.group(0).split("\n"), want.split("\n")
                for x, y in zip(a, b):
                    if x != y: print("    README: %s\n    run:    %s" % (x, y)); break
            return 1
        print("  [PASS] boundary table (%s): the README's table agrees with this run" % lang); return 0
    if m:
        text = text[:m.start()] + want + text[m.end():]
    else:
        h = "## What crosses the boundary"
        i = text.index(h)
        text = text[:i] + ("## Boundary tests\n\nThe shared tests in `tests/boundary.py`, run in this language's worker (`tests/test_boundary.sh`): one script per case, written in %s "
                           "(`containment/boundary.tsv`), and what the host saw on the wire. `ok` means the value crossed as the same JSON value; `n/a` means "
                           "the language has no way to write the case; anything else is what happened instead. Nothing in the tests lists what a worker can do.\n\n" % lang) + want + "\n" + text[i:]
    open(readme, "w", encoding="utf-8").write(text)
    print("  [PASS] boundary table (%s): wrote it" % lang); return 0

if __name__ == "__main__":
    sys.exit(main())
